"""Explicit coverage of the safety questions; never infer approval from solver success."""
import pandas as pd

from src.models import BaseFixity


def assessment(data, model, result):
    rows = []
    def add(name, status, detail):
        rows.append({"Проверка": name, "Статус": status, "Пояснение": detail})
    add("Расчётная схема", "НЕ ПОДТВЕРЖДЕНА",
        "Искусственные опоры воспринимают усилия." if not data.spatial_diagnostic else
        "Диагностика без искусственных опор; существующие вертикальные связи опирания сохранены. Это ещё не реальная пространственная схема.")
    if data.steel_grade == "UNKNOWN":
        add("Материал", "НЕ ПОДТВЕРЖДЁН",
            f"Марка стали неизвестна. Ry={data.steel_resistance_mpa:g} МПа — условное допущение, а не установленная прочность поставленного металла.")
    add("Решение МКЭ", "ВЫПОЛНЕНО" if result.ok else "НЕ ПОЛУЧЕНО", result.message)
    if result.ok:
        maximum = result.elements.elastic_NM_util.max()
        add("Упругие напряжения N + My + Mz", "ПРЕВЫШЕНИЕ" if maximum > 1 else "ЧАСТИЧНО",
            f"Максимум {maximum:.3f}. Только нормальные напряжения в принятой модели; без среза, кручения и устойчивости.")
    add("Устойчивость элементов", "НЕ ПОДТВЕРЖДЕНА",
        "Эйлер — только индикатор, не проверка СП 16. Нужны расчётные длины, закрепления, кривые устойчивости, местная устойчивость и взаимодействие N–M.")
    add("Пространственные связи", "НЕТ ДАННЫХ",
        data.project_notes.get("bracing", "Нужны координаты и соединения связей.")
        + f" Дополнительная масса из прежней спецификации без жёсткости: {model.additional_dead_mass_kg:.2f} кг; её состав требует сверки. Работа кровли как диска не задана.")
    add("Снег", "ЧАСТИЧНО", f"Сценарий: {data.snow_pattern}. Дополнительные половинные загружения исследовательские; схемы СП 20, снеговые мешки и окружение требуют проверки.")
    add("Прогибы", "НЕ ПОДТВЕРЖДЕНЫ",
        "Нужны эксплуатационное сочетание, относительные прогибы пролётов и их предельные значения. Max Uz не является такой проверкой.")
    add("Соединения", "НЕТ ДАННЫХ", "Нужны швы/болты, опорные площадки, эксцентриситеты и местная прочность стенок труб.")
    accepted_fixed = data.fixed_base_hypothesis_accepted and data.base_fixity == BaseFixity.FIXED
    add("Закрепление оснований", "ПРИНЯТА ГИПОТЕЗА" if accepted_fixed else "РАСЧЁТНОЕ ДОПУЩЕНИЕ",
        "Основания стоек: " + data.base_fixity.value
        + (". По согласованию с заказчиком запрещены все три перемещения и три поворота."
           if accepted_fixed else ". Физическая жёсткость требует обоснования."))
    add("Прочность свай, закладных и грунта", "НЕ ПРОВЕРЕНО",
        "Вынесена за рамки принятой гипотезы закрепления. "
        + data.project_notes.get("foundations", "Нужны данные оснований."))
    if "roof" in data.project_notes:
        add("Покрытие кровли", "НЕ ПРОВЕРЕНО", data.project_notes["roof"])
    add("Сочетания и второй порядок", "НЕ ПРОВЕРЕНО", "Линейный расчёт; нужны расчётные сочетания, ветер, начальные несовершенства и эффекты второго порядка.")
    return pd.DataFrame(rows)
